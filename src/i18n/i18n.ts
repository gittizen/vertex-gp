const TABLES: Record<Locale, Dict> = { cs: CS, en: EN }

let locale: Locale = loadLocale()
const listeners = new Set<() => void>()

function loadLocale(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'en' || v === 'cs') return v
  } catch {
    /* ignore */
  }
  return 'cs'
}

export function getLocale(): Locale {
  return locale
}

export function setLocale(next: Locale): void {
  if (next === locale) return
  locale = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    /* ignore */
  }
  document.documentElement.lang = next === 'cs' ? 'cs' : 'en'
  for (const cb of listeners) cb()
}

export function onLocaleChange(cb: () => void): () => void {
  listeners.add(cb)
  return () => listeners.delete(cb)
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = TABLES[locale][key] ?? TABLES.cs[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}

export function langToggleHtml(): string {
  const cs = locale === 'cs' ? 'active' : ''
  const en = locale === 'en' ? 'active' : ''
  return `
    <div class="lang-toggle" role="group" aria-label="Language">
      <button type="button" class="lang-btn ${cs}" data-lang="cs">CZ</button>
      <button type="button" class="lang-btn ${en}" data-lang="en">EN</button>
    </div>
  `
}

export function muteToggleHtml(muted: boolean): string {
  const on = !muted ? 'active' : ''
  const off = muted ? 'active' : ''
  return `
    <div class="mute-toggle" role="group" aria-label="${t('mute.on')} / ${t('mute.off')}">
      <button type="button" class="mute-btn ${on}" data-mute="0">${t('mute.on')}</button>
      <button type="button" class="mute-btn ${off}" data-mute="1">${t('mute.off')}</button>
    </div>
  `
}

export function bindLangToggle(root: ParentNode, onChange?: () => void): void {
  root.querySelectorAll<HTMLButtonElement>('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.stopPropagation()
      const lang = btn.dataset.lang as Locale
      if (lang !== 'cs' && lang !== 'en') return
      setLocale(lang)
      onChange?.()
    })
  })
}

export function bindMuteToggle(
  root: ParentNode,
  getMuted: () => boolean,
  setMuted: (muted: boolean) => void,
  onChange?: () => void,
): void {
  root.querySelectorAll<HTMLButtonElement>('[data-mute-toggle]').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.stopPropagation()
      setMuted(!getMuted())
      onChange?.()
    })
  })
  root.querySelectorAll<HTMLButtonElement>('[data-mute]').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.stopPropagation()
      const want = btn.dataset.mute === '1'
      if (want === getMuted()) return
      setMuted(want)
      onChange?.()
    })
  })
}

